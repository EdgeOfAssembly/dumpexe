#!/bin/bash
# gen_pair_table.sh OUT.h FILE... : build the verified pair table (§10.10).
# Runs dumpexe --uasm --uasm-verified on each file with DUMPEXE_PAIR_DUMP set,
# then keeps every shape key that stayed mnemonic in all its instances.
set -u
OUT=$1; shift
BIN=$(realpath "${DUMPEXE_BIN:-$(dirname "$0")/../dumpexe}")
UASM_BIN=${UASM_BIN:-/workspace/uasm-src/GccUnixR/uasm}
T=$(mktemp -d); trap 'rm -rf "$T"' EXIT
i=0
for f in "$@"; do
  i=$((i+1)); mkdir -p "$T/$i"; cp "$f" "$T/$i/"
  (cd "$T/$i" && env -u UASM DUMPEXE_PAIR_DUMP="$T/$i.pairs" timeout 600 "$BIN" --uasm --uasm-verified \
      --uasm-bin "$UASM_BIN" -o out.asm "$(basename "$f")" >/dev/null 2>&1) &
  (( i % 4 == 0 )) && wait
done
wait
cat "$T"/*.pairs 2>/dev/null | awk '{ n[$1]++; ok[$1]+=$2 } END { for (k in n) if (ok[k]==n[k]) print k }' \
  | LC_ALL=C sort > "$T/keys"
{
  echo '#pragma once'
  echo '/**'
  echo ' * @file pair_table.h'
  echo ' * @brief Verified pair table (§10.10): instruction shapes whose mnemonic'
  echo ' *        spelling reassembled byte-identically in every corpus verify run.'
  echo ' *        Generated by tools/gen_pair_table.sh; used only when UASM is absent.'
  echo ' */'
  echo '#include <string_view>'
  echo
  echo 'namespace dx'
  echo '{'
  echo 'inline constexpr std::string_view kVerifiedPairs[] = {'
  sed 's/.*/    "&",/' "$T/keys"
  echo '};'
  echo '} // namespace dx'
} > "$OUT"
echo "pairs: $(wc -l < "$T/keys") shapes"
