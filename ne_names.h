/**
 * @brief Name of an ordinal export of KERNEL, USER or GDI, or nullptr.
 */
inline const char* ne_builtin_ordinal_name(std::string_view module, uint16_t ord)
{
    std::span<const NeOrdName> t;
    if (module == "KERNEL")
        t = kNeKernelNames;
    else if (module == "USER")
        t = kNeUserNames;
    else if (module == "GDI")
        t = kNeGdiNames;
    else
        return nullptr;
    auto it = std::lower_bound(t.begin(), t.end(), ord,
                               [](const NeOrdName& a, uint16_t o) { return a.ord < o; });
    return (it != t.end() && it->ord == ord) ? it->name : nullptr;
}

